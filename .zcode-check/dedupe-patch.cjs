let total = 0
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json'))) {
  const lang = f.replace('.json', '')
  const patch = P[lang]
  if (!patch) { console.log(f + ': no patch, skipped'); continue }
  const p = path.join(dir, f)
  const j = JSON.parse(fs.readFileSync(p, 'utf8'))
  let applied = 0
  for (const [key, value] of Object.entries(patch)) {
    const parts = key.split('.')
    let o = j
    for (let i = 0; i < parts.length - 1; i++) {
      if (!(parts[i] in o)) { console.log(f + ': MISSING PATH ' + key); continue }
      o = o[parts[i]]
    }
    const last = parts[parts.length - 1]
    if (!(last in o)) { console.log(f + ': MISSING KEY ' + key) }
    o[last] = value
    applied++
  }
  fs.writeFileSync(p, JSON.stringify(j, null, 2) + '\n', 'utf8')
  console.log(f + ': ' + applied + ' keys patched')
  total += applied
}
console.log('TOTAL: ' + total + ' keys across ' + Object.keys(P).length + ' languages')
